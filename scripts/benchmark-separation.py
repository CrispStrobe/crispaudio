#!/usr/bin/env python3
"""Measure CrispASR stem separation with known ground truth.

Speech: Harvard sentences synthesised by alternating local TTS engines (exact
reference text). Music: a generated polyphonic piece with an exact note list,
plus an optional real instrumental track. Pairs are mixed at several
speech-to-music ratios and separated through `crispaudio separate-audio` (the
app's code path) with each separation model. Against the clean sources we report

  * SI-SDR of speech/music stems (music stem = sum of all non-vocal stems),
  * leakage: what each separator puts in the wrong stem for clean speech/music,
  * ASR word error rate (several ASR models) on clean speech, mix and vocals,
  * note-transcription F1 (onset +-50 ms, same MIDI pitch) with several
    transcribers on clean music, mix and music stem. Generated music is scored
    against its true notes; real music against the transcriber's own output on
    the clean track ("before" vs "after").

Not a listening test. Requires numpy and macOS afconvert, plus:
  CRISPASR_BIN        crispasr CLI (TTS, ASR, note transcription)
  CRISPAUDIO_CLI      crispaudio CLI (separation)
  CRISPASR_LIB        libcrispasr used by crispaudio
  CRISPASR_MODEL_DIRS colon-separated folders searched for model files
Usage: benchmark-separation.py OUT_DIR [--music TRACK] [--ratios 6,0,-6] [--slow]
"""
import argparse, json, os, re, struct, subprocess, sys, time
from pathlib import Path
import numpy as np

RATE = 48000
DISCLOSURE = re.compile(r"this audio was generated by artificial intelligence\.?", re.I)
# Harvard sentences (IEEE 1969 recommended practice), lists 1-2: public domain.
SENTENCES = [
    "The birch canoe slid on the smooth planks.", "Glue the sheet to the dark blue background.",
    "It is easy to tell the depth of a well.", "These days a chicken leg is a rare dish.",
    "Rice is often served in round bowls.", "The juice of lemons makes fine punch.",
    "The box was thrown beside the parked truck.", "The hogs were fed chopped corn and garbage.",
    "Four hours of steady work faced us.", "A large size in stockings is hard to sell.",
    "The boy was there when the sun rose.", "A rod is used to catch pink salmon.",
]
VOICES = [("piper", "piper-en_US-lessac-medium-f16.gguf", []), ("melotts", "melotts-en-q8.gguf", []),
          ("kokoro", "auto", ["--auto-download", "--voice", "@kokoro-voice-af_heart.gguf"])]
ASRS = {"parakeet-tdt-v3-q4k": "parakeet-tdt-0.6b-v3-q4_k.gguf", "whisper-large-v3-turbo": "ggml-large-v3-turbo.bin",
        "qwen3-asr-0.6b": "qwen3-asr-0.6b-q4_k.gguf"}
SEPARATORS = {"mel-band-roformer": "mel-band-roformer-vocals-f16.gguf", "htdemucs": "htdemucs-q4_k.gguf",
              "mini-bs-roformer": "mini-bs-roformer-q8_0.gguf"}
TRANSCRIBERS = ["basic-pitch", "piano-transcription", "onsets-and-frames", "mt3"]

def env(name):
    value = os.environ.get(name)
    if not value:
        sys.exit(f"{name} is required")
    return value

def run(args):
    return subprocess.run([str(a) for a in args], check=True, capture_output=True, text=True)

def model(name, dirs):
    for d in dirs:
        if (Path(d) / name).is_file():
            return str(Path(d) / name)
    sys.exit(f"model {name} not found in {dirs}")

def read_wav(path):
    b = Path(path).read_bytes(); i = 12; ch = rate = fmt = 0
    while i < len(b):
        cid = b[i:i + 4]; size = struct.unpack("<I", b[i + 4:i + 8])[0]
        if cid == b"fmt ":
            fmt, ch, rate = struct.unpack("<HHI", b[i + 8:i + 16])
            if fmt == 0xFFFE:
                fmt = struct.unpack("<H", b[i + 32:i + 34])[0]
        if cid == b"data":
            raw = b[i + 8:i + 8 + size]
            x = np.frombuffer(raw, "<f4").astype(np.float64) if fmt == 3 else np.frombuffer(raw, "<i2") / 32768.0
            return x.reshape(-1, ch).T, rate
        i += 8 + size + (size & 1)
    raise ValueError(f"no data in {path}")

def write_wav(path, x, rate=RATE):
    x = np.atleast_2d(np.asarray(x, dtype="<f4")); d = x.T.tobytes(); ch = x.shape[0]
    Path(path).write_bytes(b"RIFF" + struct.pack("<I", 36 + len(d)) + b"WAVEfmt " +
        struct.pack("<IHHIIHH", 16, 3, ch, rate, rate * 4 * ch, 4 * ch, 32) + b"data" + struct.pack("<I", len(d)) + d)
    return path

def to48k(src, dst, channels):
    run(["afconvert", "-f", "WAVE", "-d", "LEF32@48000", "-c", str(channels), src, dst])
    return read_wav(dst)[0]

def si_sdr(ref, est):
    ref = ref - ref.mean(); est = est - est.mean()
    a = np.dot(est, ref) / np.dot(ref, ref); t = a * ref
    return float(10 * np.log10(np.sum(t ** 2) / np.sum((est - t) ** 2)))

def db(x):
    return float(10 * np.log10(np.mean(np.square(x)) + 1e-20))

def words(text):
    text = DISCLOSURE.sub(" ", re.sub(r"\[[^\]]*\]", " ", text))
    return re.sub(r"[^a-z' ]", " ", text.lower().replace("-", " ")).split()

def wer(ref, hyp):
    r, h = words(ref), words(hyp)
    d = list(range(len(h) + 1))
    for i in range(1, len(r) + 1):
        prev, d[0] = d[0], i
        for j in range(1, len(h) + 1):
            prev, d[j] = d[j], min(d[j] + 1, d[j - 1] + 1, prev + (r[i - 1] != h[j - 1]))
    return d[len(h)] / len(r)

def note_f1(truth, found, tolerance=0.05):
    if not truth:
        return None
    used = set(); hits = 0
    for t in truth:
        best = None
        for k, f in enumerate(found):
            if k not in used and f["midi"] == t["midi"]:
                gap = abs(f["onset"] - t["onset"])
                if gap <= tolerance and (best is None or gap < best[0]):
                    best = (gap, k)
        if best:
            used.add(best[1]); hits += 1
    p = hits / len(found) if found else 0.0; r = hits / len(truth)
    return round(2 * p * r / (p + r), 3) if p + r else 0.0

def generated_music(duration, seed=3):
    """Piano-like additive synthesis; returns stereo PCM and exact notes."""
    rng = np.random.default_rng(seed); beat = 60 / 100
    chords = [[48, 52, 55], [45, 48, 52], [41, 45, 48], [43, 47, 50]]  # C Am F G
    scale = [60, 62, 64, 65, 67, 69, 71, 72, 74, 76]
    notes = []; t0 = 0.5; bar = 0
    while t0 + 2 * beat < duration - 0.5:
        for m in chords[bar % 4]:
            notes.append({"onset": t0, "offset": t0 + 2 * beat * 0.95, "midi": m, "velocity": 0.5})
        for k in range(4):
            notes.append({"onset": t0 + k * beat / 2, "offset": t0 + (k + 1) * beat / 2 * 0.98,
                          "midi": int(rng.choice(scale)), "velocity": 0.7})
        t0 += 2 * beat; bar += 1
    pcm = np.zeros((2, int(duration * RATE)))
    for n in notes:
        f0 = 440 * 2 ** ((n["midi"] - 69) / 12); i0 = int(n["onset"] * RATE); length = int((n["offset"] - n["onset"]) * RATE)
        tt = np.arange(length) / RATE
        envelope = np.exp(-tt * 3) * np.minimum(1, tt / 0.004) * np.minimum(1, (length - np.arange(length)) / 400)
        tone = sum(np.sin(2 * np.pi * f0 * h * tt) / h ** 1.3 for h in range(1, 7)) * envelope * n["velocity"]
        pan = 0.3 + 0.4 * ((n["midi"] - 40) / 40)
        pcm[0, i0:i0 + length] += tone * (1 - pan); pcm[1, i0:i0 + length] += tone * pan
    return pcm, notes

class Bench:
    def __init__(self, args):
        self.crispasr, self.cli = env("CRISPASR_BIN"), env("CRISPAUDIO_CLI"); env("CRISPASR_LIB")
        self.dirs = env("CRISPASR_MODEL_DIRS").split(":")
        self.work = Path(args.out); self.work.mkdir(parents=True, exist_ok=True)
        self.transcribers = TRANSCRIBERS + (["hft-transformer"] if args.slow else [])
        self.timing = {}

    def timed(self, key, fn):
        start = time.time(); result = fn(); self.timing.setdefault(key, []).append(time.time() - start); return result

    def tts(self, index, text):
        name, file, extra = VOICES[index % len(VOICES)]
        extra = [model(e[1:], self.dirs) if e.startswith("@") else e for e in extra]
        out = self.work / f"tts-{index}.wav"
        run([self.crispasr, "--backend", name, "-m", file if file == "auto" else model(file, self.dirs), *extra, "--tts", text, "--tts-output", out])
        pcm = to48k(out, self.work / f"tts-{index}-48k.wav", 1)[0]
        return pcm / np.sqrt(np.mean(pcm ** 2)) * 10 ** (-20 / 20)

    def asr(self, path):
        out = {}
        for name, file in ASRS.items():
            text = self.timed(f"asr:{name}", lambda: run([self.crispasr, "-m", model(file, self.dirs), "-f", path, "-np", "-l", "en"]).stdout)
            out[name] = " ".join(line.strip() for line in text.splitlines() if line.strip())
        return out

    def notes(self, path):
        out = {}
        for backend in self.transcribers:
            text = self.timed(f"notes:{backend}", lambda: run([self.crispasr, "--piano", "--backend", backend, "-m", "auto", "--auto-download", "--piano-format", "json", "-f", path]).stdout)
            data = json.loads(text[text.index("{"):])
            out[backend] = [{"onset": n["onset"], "midi": n["midi"]} for n in data.get("notes", [])]
        return out

    def separate(self, separator, path, folder):
        folder.mkdir(parents=True, exist_ok=True)
        listing = self.timed(f"separate:{separator}", lambda: json.loads(run([self.cli, "separate-audio", "--input", path, "--model", model(SEPARATORS[separator], self.dirs), "--output-dir", folder]).stdout))
        stems = {s["stem"]: read_wav(s["path"])[0] for s in listing["stems"]}
        vocals = stems.pop("vocals")
        return vocals, sum(stems.values()), sorted(stems)

def main():
    parser = argparse.ArgumentParser(); parser.add_argument("out"); parser.add_argument("--music")
    parser.add_argument("--ratios", default="6,0,-6"); parser.add_argument("--slow", action="store_true")
    args = parser.parse_args(); b = Bench(args); w = b.work
    gap = np.zeros(int(0.5 * RATE)); parts = []
    for i, sentence in enumerate(SENTENCES):
        parts += [b.tts(i, sentence), gap]
    speech = np.concatenate(parts); reference = " ".join(SENTENCES); duration = len(speech) / RATE
    print(f"speech {duration:.1f}s from {len(VOICES)} TTS engines", flush=True)

    musics = {"generated": generated_music(duration)}
    if args.music:
        real = to48k(args.music, w / "real-full.wav", 2); start = min(int(30 * RATE), max(0, real.shape[1] - len(speech)))
        if real.shape[1] - start < len(speech):
            sys.exit("real music is shorter than the speech")
        musics["real"] = (real[:, start:start + len(speech)], None)

    results = {"duration": duration, "voices": [v[0] for v in VOICES], "asr": list(ASRS), "separators": list(SEPARATORS),
               "transcribers": b.transcribers, "speech": {}, "music": {}, "cases": []}
    write_wav(w / "speech.wav", speech)
    results["speech"]["cleanWer"] = {k: round(wer(reference, v), 4) for k, v in b.asr(w / "speech.wav").items()}
    for sep in SEPARATORS:  # leakage: clean speech should leave the music stem silent
        vocals, music_stem, names = b.separate(sep, w / "speech.wav", w / f"speech-{sep}")
        results["speech"].setdefault("musicStemLeakDb", {})[sep] = round(db(music_stem) - db(speech), 1)
        print(f"speech-only {sep}: music stem {results['speech']['musicStemLeakDb'][sep]} dB re speech ({names})", flush=True)

    for name, (music, truth) in musics.items():
        music = music / np.sqrt(np.mean(music ** 2)) * 10 ** (-20 / 20)
        clean_path = write_wav(w / f"music-{name}.wav", music)
        clean_notes = b.notes(write_wav(w / f"music-{name}-mono.wav", music.mean(0)))
        reference_notes = {k: truth for k in clean_notes} if truth else clean_notes
        info = {"cleanNoteF1": {k: note_f1(truth, v) for k, v in clean_notes.items()} if truth else None, "vocalsStemLeakDb": {}}
        for sep in SEPARATORS:  # leakage: clean music should leave the vocals stem silent
            vocals, _, _ = b.separate(sep, clean_path, w / f"music-{name}-{sep}")
            info["vocalsStemLeakDb"][sep] = round(db(vocals) - db(music), 1)
        results["music"][name] = info; print(f"music {name}: {json.dumps(info)}", flush=True)
        for ratio in [float(r) for r in args.ratios.split(",")]:
            tag = f"{name}{ratio:+g}dB"; folder = w / tag; folder.mkdir(exist_ok=True)
            m_scaled = music * 10 ** (-ratio / 20)
            mix = np.vstack([speech, speech]) + m_scaled
            scale = min(1.0, 0.98 / np.max(np.abs(mix))); mix *= scale; s_ref = speech * scale; m_ref = m_scaled.mean(0) * scale
            mix_path = write_wav(folder / "mix.wav", mix); mix_mono = write_wav(folder / "mix-mono.wav", mix.mean(0))
            mix_asr = b.asr(mix_mono); mix_notes = b.notes(mix_mono)
            for sep in SEPARATORS:
                vocals, music_stem, _ = b.separate(sep, mix_path, folder / sep)
                vocal_asr = b.asr(write_wav(folder / sep / "vocals-mono.wav", vocals.mean(0)))
                stem_notes = b.notes(write_wav(folder / sep / "music-mono.wav", music_stem.mean(0)))
                case = {"music": name, "speechToMusicDb": ratio, "separator": sep,
                    "speechSiSdr": {"mix": round(si_sdr(s_ref, mix.mean(0)), 2), "stem": round(si_sdr(s_ref, vocals.mean(0)), 2)},
                    "musicSiSdr": {"mix": round(si_sdr(m_ref, mix.mean(0)), 2), "stem": round(si_sdr(m_ref, music_stem.mean(0)), 2)},
                    "wer": {a: {"mix": round(wer(reference, mix_asr[a]), 4), "stem": round(wer(reference, vocal_asr[a]), 4)} for a in ASRS},
                    "noteF1": {t: {"mix": note_f1(reference_notes[t], mix_notes[t]), "stem": note_f1(reference_notes[t], stem_notes[t])} for t in b.transcribers},
                    "transcripts": {"mix": mix_asr, "stem": vocal_asr}}
                results["cases"].append(case)
                print(json.dumps({k: v for k, v in case.items() if k != "transcripts"}), flush=True)
                (w / "results.json").write_text(json.dumps(results, indent=2))
    results["meanSeconds"] = {k: round(sum(v) / len(v), 1) for k, v in b.timing.items()}
    (w / "results.json").write_text(json.dumps(results, indent=2))
    print(json.dumps(results["meanSeconds"]))

if __name__ == "__main__":
    main()
